  vi('Tiếng Việt', 'vi'),
  en('English', 'en'),
  es('Español', 'es'),
  zh('中文', 'zh'),
  ja('日本語', 'ja'),
  ko('한국어', 'ko');

  final String name;
  final String code;
  const AppLanguage(this.name, this.code);

  static AppLanguage fromCode(String code) {
    return AppLanguage.values.firstWhere(
      (lang) => lang.code == code,
      orElse: () => AppLanguage.vi,
    );
  }
}

